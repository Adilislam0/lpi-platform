--
-- WHY THIS TABLE EXISTS
-- ─────────────────────
-- Yashika's Phase 4 feedback loop needs somewhere to record when a user
-- accepts or dismisses a recommendation, so that choice can influence
-- future suggestions (e.g. don't keep re-surfacing something the user
-- already dismissed).
--
-- IMPORTANT — recommendations are NOT persisted anywhere.
-- lpi/recommendation_engine.py builds Recommendation objects on the fly on
-- every GET /api/v1/recommendations/{user_id} call, with a fresh
-- uuid4() id each time (see generate_recommendations() / sort + slice in
-- routers/recommendations.py). There is no `recommendations` table to
-- foreign-key against, and a recommendation_id is only ever meaningful in
-- the context of the API response the frontend rendered it from.
--
-- Because of that, this table SNAPSHOTS the parts of the recommendation
-- the user actually reacted to (action, smile_phase) instead of relying on
-- a join back to a row that won't exist by the time anyone reads this
-- table later. recommendation_id is still stored — it's useful for
-- deduplicating "did we already record feedback for this exact card" within
-- a single response — but it is NOT a foreign key.
--
-- FIELD DESIGN
-- ─────────────
-- recommendation_id : The ephemeral id from the Recommendation object the
--                      user was looking at. Not unique across time (every
--                      GET call mints new ids for what may be the "same"
--                      logical suggestion) — only unique within one
--                      response. No FK; see above.
--
-- action            : Snapshot of Recommendation.action at the moment of
--                      feedback. Keeps a feedback row self-describing even
--                      though the original recommendation is gone moments
--                      after the response was sent.
--
-- smile_phase        : Snapshot of Recommendation.smile_phase. Same 6-phase
--                      CHECK constraint as goals/activity_signals-adjacent
--                      tables, so a bad phase string can't sneak in here
--                      either (see models.SmilePhase / the hallucinated
--                      5-phase regression this project has already had to
--                      correct once).
--
-- status             : 'accepted' or 'dismissed'. The two reactions named
--                      explicitly in the Phase 4 plan ("when a user
--                      accepts or dismisses a recommendation").
--
-- No UNIQUE constraint on recommendation_id: a user could plausibly change
-- their mind (accept, then later dismiss), and that history is useful
-- signal for "future suggestions" rather than noise to dedupe away. If
-- Yashika's endpoint wants upsert-on-id semantics instead, that's an
-- application-layer decision, not a schema-layer one.
--
-- HOW TO APPLY THIS MIGRATION
-- ─────────────────────────────
-- Local dev:   supabase db push     (applies all unapplied migrations)
-- Verify:      supabase status      (check migration is listed)
